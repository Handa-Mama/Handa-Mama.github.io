"""
හඳ මාමා කතන්දර — recorded narration for "read to me"

Makes one MP3 for every paragraph the app reads aloud (book titles, story pages, the lesson
and the goodnight wish), so stories are read aloud on every device, including iPhones and
computers that have no Sinhala voice of their own. Runs in GitHub Actions (narrate.yml):

    pip install edge-tts
    python tools/narrate.py            # only makes clips that are missing

Each clip is named after a hash of its text (the app computes the same hash), so editing a
story only re-records the paragraphs that changed. Writes audio/<hash>.mp3 and data/narration.js.
"""
import asyncio, json, os, re, sys

import edge_tts

VOICE = os.environ.get('NARRATION_VOICE', 'si-LK-SameeraNeural')
RATE = os.environ.get('NARRATION_RATE', '-10%')
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
AUDIO = os.path.join(ROOT, 'audio')


def fnv(text):
    """FNV-1a, 32 bit, over the UTF-8 bytes: the same as hashText() in js/app.js"""
    h = 0x811c9dc5
    for b in text.encode('utf-8'):
        h ^= b
        h = (h * 0x01000193) & 0xffffffff
    return '%08x' % h


def norm(t):
    return re.sub(r'\s+', ' ', t).strip()


def texts():
    src = open(os.path.join(ROOT, 'data', 'stories.js'), encoding='utf-8').read()
    books = json.loads(src[src.index('['):src.rindex(']') + 1])
    out = []
    for b in books:
        out += [b['title']] + ([b['subtitle']] if b.get('subtitle') else [])
        for p in b['pages']:
            out += p['paras']
        out += [b['moral'], b.get('goodnight') or 'සුබ රාත්‍රියක්!']
    return [n for n in dict.fromkeys(norm(t) for t in out) if n]


async def record(text, path):
    for attempt in range(5):
        try:
            await edge_tts.Communicate(text, VOICE, rate=RATE).save(path + '.part')
            if os.path.getsize(path + '.part') < 1000:
                raise RuntimeError('empty clip')
            os.replace(path + '.part', path)
            return
        except Exception as e:  # the speech service drops connections now and then
            print('  retry', attempt + 1, e, file=sys.stderr)
            await asyncio.sleep(2 * (attempt + 1))
    raise RuntimeError('could not record: ' + text[:40])


async def main():
    os.makedirs(AUDIO, exist_ok=True)
    want = {fnv(t): t for t in texts()}
    missing = [(h, t) for h, t in want.items() if not os.path.exists(os.path.join(AUDIO, h + '.mp3'))]
    print(f'{len(want)} paragraphs, {len(missing)} to record with {VOICE}')
    sem = asyncio.Semaphore(4)

    async def one(h, t):
        async with sem:
            await record(t, os.path.join(AUDIO, h + '.mp3'))
            print('  recorded', h, t[:30])
    await asyncio.gather(*(one(h, t) for h, t in missing))
    # clips for text that is no longer in any story
    for f in os.listdir(AUDIO):
        if f.endswith('.mp3') and f[:-4] not in want:
            os.remove(os.path.join(AUDIO, f))
    clips = sorted(want)
    with open(os.path.join(ROOT, 'data', 'narration.js'), 'w', encoding='utf-8') as f:
        f.write('/* generated by tools/narrate.py — recorded narration clips (audio/<hash>.mp3) */\n')
        f.write('window.HM_NARRATION = ' + json.dumps({'voice': VOICE, 'clips': clips}) + ';\n')
    print('done:', len(clips), 'clips')


asyncio.run(main())
