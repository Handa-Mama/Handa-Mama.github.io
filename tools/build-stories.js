#!/usr/bin/env node
/*
 * හඳ මාමා කතන්දර — story builder
 *
 * Turns the plain-text stories in /stories into book data for the website.
 *   node tools/build-stories.js
 *
 * Text file format (same as the original sample stories):
 *   line 1            title  (optional subtitle after " – ")
 *   paragraphs        the story, separated by blank lines or line breaks
 *   "මෙම කතාවෙන් …"    the moral   → its own lesson page
 *   "සුබ රාත්‍රියක් …"  goodnight   → the last page
 *
 * Output: data/stories.json and data/stories.js (same data, the .js version
 * lets the site run straight from a folder without a web server).
 */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(ROOT, 'stories');
const OUT = path.join(ROOT, 'data');

const MAX_WORDS = 42;   // most words on one book page
const MIN_WORDS = 14;   // shorter paragraphs join their neighbour when they fit

const MORAL_START = 'මෙම කතාවෙන්';
const GOODNIGHT_START = 'සුබ රාත්‍රියක්';
const ZWJ = '‍';

const config = JSON.parse(fs.readFileSync(path.join(SRC, 'stories.config.json'), 'utf8'));
const words = (s) => s.trim().split(/\s+/).filter(Boolean).length;

// Split a paragraph into sentences, keeping closing quotes with their sentence.
function sentences(p) {
  const out = p.match(/[^.!?…]+(?:[.!?…]+[”"']?|$)\s*/g) || [p];
  return out.map((s) => s).filter((s) => s.trim());
}

// Break long paragraphs at sentence ends so no page is over MAX_WORDS.
function chunkParagraph(p) {
  const chunks = [];
  let cur = '';
  for (const s of sentences(p)) {
    if (cur && words(cur + s) > MAX_WORDS) { chunks.push(cur.trim()); cur = ''; }
    cur += s;
  }
  if (cur.trim()) chunks.push(cur.trim());
  // avoid a tiny last chunk: move it back if it fits
  if (chunks.length > 1 && words(chunks[chunks.length - 1]) < 10 &&
      words(chunks[chunks.length - 2]) + words(chunks[chunks.length - 1]) <= MAX_WORDS + 10) {
    const last = chunks.pop();
    chunks[chunks.length - 1] += ' ' + last;
  }
  return chunks;
}

function zwjWarnings(text, file) {
  // al-lakuna (්) followed directly by ර or ය usually needs a ZWJ for rakaransaya / yansaya
  // (ර් before another letter is repaya, which needs no joiner, so it is skipped)
  const bad = text.match(/[඀-෿]*[ක-ය඼-ෆ]්(?!‍)[රය][඀-෿]*/g);
  if (bad) {
    console.warn(`  ! ${file}: these words may be missing a hidden joiner (ZWJ) and could display wrongly:`);
    [...new Set(bad)].forEach((w) => console.warn('      ' + w));
  }
}

const books = [];
for (const [file, meta] of Object.entries(config)) {
  if (file.startsWith('_')) continue;
  const txtPath = path.join(SRC, file + '.txt');
  if (!fs.existsSync(txtPath)) { console.warn(`  ! missing ${file}.txt — skipped`); continue; }
  const raw = fs.readFileSync(txtPath, 'utf8').replace(/\r\n?/g, '\n').replace(/^﻿/, '');
  zwjWarnings(raw, file);

  const paras = raw.split('\n').map((s) => s.trim()).filter(Boolean);
  const [titleLine, ...rest] = paras;
  const [title, subtitle] = titleLine.split(/\s+[–—-]\s+/);

  let moral = null;
  let goodnight = null;
  const body = [];
  for (const p of rest) {
    if (p.startsWith(MORAL_START)) moral = p;
    else if (p.startsWith(GOODNIGHT_START)) goodnight = p;
    else body.push(p);
  }

  const scenes = meta.scenes || [];
  const sceneFor = (i) => scenes[Math.min(i, scenes.length - 1)] || 'night-sky';

  // paragraphs → page chunks (each chunk remembers its paragraph for the picture)
  const chunks = [];
  body.forEach((p, i) => chunkParagraph(p).forEach((c) => chunks.push({ text: c, para: i })));

  // join very short chunks with a neighbour when the result still fits
  const pages = [];
  for (const c of chunks) {
    const prev = pages[pages.length - 1];
    const short = words(c.text) < MIN_WORDS;
    if (prev && (short || words(prev.paras[prev.paras.length - 1]) < MIN_WORDS) &&
        words(prev.paras.join(' ')) + words(c.text) <= MAX_WORDS) {
      prev.paras.push(c.text);
    } else {
      pages.push({ paras: [c.text], scene: sceneFor(c.para) });
    }
  }
  if (pages[0]) pages[0].dropCap = true;

  books.push({
    id: meta.id,
    file,
    title: title.trim(),
    subtitle: subtitle ? subtitle.trim() : null,
    ages: meta.ages,
    color: meta.color,
    cover: meta.cover,
    long: !!meta.long,
    pages,
    moral,
    goodnight,
  });
  console.log(`  ✓ ${title.trim()} — ${pages.length} story pages`);
}

fs.mkdirSync(OUT, { recursive: true });
const json = JSON.stringify(books, null, 1);
fs.writeFileSync(path.join(OUT, 'stories.json'), json);
fs.writeFileSync(path.join(OUT, 'stories.js'),
  '/* generated by tools/build-stories.js — edit the .txt files in /stories instead */\nwindow.HM_STORIES = ' + json + ';\n');
console.log(`Built ${books.length} books → data/stories.json, data/stories.js`);
